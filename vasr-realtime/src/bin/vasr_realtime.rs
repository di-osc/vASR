use std::fs::OpenOptions;
use std::io::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use clap::{Args, Parser, Subcommand};
use vasr_realtime::{DEFAULT_CONFIG_TOML, VasrConfig, init_logging, run_realtime_config};

#[derive(Debug, Parser)]
#[command(
    name = "vasr-realtime",
    version,
    about = "vASR realtime WebSocket service"
)]
struct Cli {
    /// Show VAD, ASR, and other component runtime logs.
    #[arg(long, short, global = true)]
    verbose: bool,

    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Generate a TOML configuration for the realtime service.
    Init(InitArgs),
    /// Load the TOML configuration and start the realtime WebSocket service.
    Serve(ServeArgs),
}

#[derive(Debug, Args)]
struct InitArgs {
    /// Configuration file to create.
    #[arg(default_value = "realtime.cfg")]
    cfg: PathBuf,

    /// Replace an existing configuration file.
    #[arg(long)]
    force: bool,
}

#[derive(Debug, Args)]
struct ServeArgs {
    /// TOML configuration file generated by `vasr-realtime init`.
    cfg: PathBuf,
}

#[tokio::main]
async fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Init(args) => {
            write_default_config(&args.cfg, args.force)?;
            println!("Created {}", args.cfg.display());
            Ok(())
        }
        Command::Serve(args) => {
            let config = VasrConfig::load(&args.cfg)?;
            init_logging(cli.verbose);
            run_realtime_config(config).await
        }
    }
}

fn write_default_config(path: &Path, force: bool) -> Result<()> {
    if path.as_os_str().is_empty() {
        bail!("config path must not be empty");
    }
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("failed to create config directory {}", parent.display()))?;
    }
    let mut options = OpenOptions::new();
    options.write(true).create(true);
    if force {
        options.truncate(true);
    } else {
        options.create_new(true);
    }
    let mut file = options.open(path).with_context(|| {
        if path.exists() && !force {
            format!(
                "config {} already exists; pass --force to replace it",
                path.display()
            )
        } else {
            format!("failed to create config {}", path.display())
        }
    })?;
    file.write_all(DEFAULT_CONFIG_TOML.as_bytes())
        .with_context(|| format!("failed to write config {}", path.display()))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use clap::{CommandFactory, Parser};

    use super::{Cli, Command};

    #[test]
    fn cli_definition_is_valid() {
        Cli::command().debug_assert();
    }

    #[test]
    fn init_defaults_to_realtime_cfg() {
        let cli = Cli::try_parse_from(["vasr-realtime", "init"]).unwrap();
        let Command::Init(args) = cli.command else {
            panic!("expected init command");
        };
        assert_eq!(args.cfg, std::path::PathBuf::from("realtime.cfg"));
        assert!(!args.force);
    }

    #[test]
    fn serve_requires_cfg() {
        let error = Cli::try_parse_from(["vasr-realtime", "serve"]).unwrap_err();
        assert_eq!(
            error.kind(),
            clap::error::ErrorKind::MissingRequiredArgument
        );
    }

    #[test]
    fn serve_accepts_cfg() {
        let cli = Cli::try_parse_from(["vasr-realtime", "serve", "custom.cfg"]).unwrap();
        let Command::Serve(args) = cli.command else {
            panic!("expected serve command");
        };
        assert_eq!(args.cfg, std::path::PathBuf::from("custom.cfg"));
    }

    #[test]
    fn init_accepts_cfg_as_a_positional_argument() {
        let cli = Cli::try_parse_from(["vasr-realtime", "init", "custom.cfg"]).unwrap();
        let Command::Init(args) = cli.command else {
            panic!("expected init command");
        };
        assert_eq!(args.cfg, std::path::PathBuf::from("custom.cfg"));
    }

    #[test]
    fn cfg_is_not_a_named_option() {
        for command in ["init", "serve"] {
            let error = Cli::try_parse_from(["vasr-realtime", command, "--cfg", "custom.cfg"])
                .unwrap_err();
            assert_eq!(error.kind(), clap::error::ErrorKind::UnknownArgument);
        }
    }

    #[test]
    fn bare_command_does_not_start_the_service() {
        let error = Cli::try_parse_from(["vasr-realtime"]).unwrap_err();
        assert_eq!(
            error.kind(),
            clap::error::ErrorKind::DisplayHelpOnMissingArgumentOrSubcommand
        );
    }
}
